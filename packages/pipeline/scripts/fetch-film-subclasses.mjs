/**
 * M1 1.1 — Pull the subclass closure of "film" (Q11424) once and write it
 * to a static file.
 *
 * The roadmap is explicit that this must not be resolved at runtime: the
 * query service has a 60 second timeout and is unusable for anything on
 * the import path. This is a build-time artefact, checked into the repo,
 * refreshed by hand when it needs to be.
 *
 * Filtering on wdt:P31 wd:Q11424 alone was the measurement query, not the
 * import filter. Documentaries, animated films and shorts are their own
 * classes and would be missing (M1, Fallstricke).
 *
 *   node scripts/fetch-film-subclasses.mjs
 */
import { writeFile } from 'node:fs/promises';
import path from 'node:path';

const ENDPOINT = 'https://query.wikidata.org/sparql';
const OUT = path.join(import.meta.dirname, '..', 'src', 'wikidata', 'film-subclasses.json');

const QUERY = `SELECT DISTINCT ?sub WHERE { ?sub wdt:P279* wd:Q11424 . }`;

const USER_AGENT =
  'BingeLog/0.1 (https://github.com/sunflower-tech/bingelog; catalog import) node-fetch';

const response = await fetch(`${ENDPOINT}?query=${encodeURIComponent(QUERY)}`, {
  headers: { Accept: 'application/sparql-results+json', 'User-Agent': USER_AGENT },
});

if (!response.ok) {
  throw new Error(`SPARQL request failed: ${String(response.status)} ${response.statusText}`);
}

const body = await response.json();

const ids = body.results.bindings
  .map((row) => row.sub.value.replace('http://www.wikidata.org/entity/', ''))
  .filter((id) => /^Q\d+$/.test(id))
  .sort((a, b) => Number(a.slice(1)) - Number(b.slice(1)));

if (ids.length < 50) {
  throw new Error(`only ${String(ids.length)} subclasses returned; the query looks wrong`);
}

await writeFile(
  OUT,
  `${JSON.stringify(
    {
      $comment:
        'Generated by scripts/fetch-film-subclasses.mjs. Do not edit by hand. ' +
        'Subclass closure of Q11424 (film), used as the dump filter in M1 1.1.',
      root: 'Q11424',
      query: QUERY,
      count: ids.length,
      ids,
    },
    null,
    2,
  )}\n`,
);

console.log(`wrote ${String(ids.length)} film subclasses to ${OUT}`);
